# The goal bank (Mercury decisions 97-118): supabase/bank/*.json -> supabase/scheduling-v42-bank.sql
# Every template goes into Mercury's library as a draft ("טיוטה – לבדיקת מטפל/ת") until the admin approves it.
# Safe to run the SQL again: an existing template keeps what was changed in it (only an old one with no content is filled).
# Run: python tools/bank-sql.py
import io, json, glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGES = ['2-5', '5-8', '8-12']
GOAL_FIELDS = ['targets', 'steps', 'principles', 'sentences', 'seen', 'needs', 'why', 'why_staff', 'method']
PARTS = ['avoid', 'signs', 'calm', 'routine']
METHODS = [
    ('ARC', 'Attachment, Regulation and Competency: מסגרת לעבודה עם ילדים אחרי טראומה מורכבת, בתוך המערכת שמטפלת בהם.\nשלושה תחומים: התקשרות (מבוגרים קשובים ועקביים), ויסות (זיהוי רגשות והרגעה), ומסוגלות (זהות, בחירה ותפקוד).\nמתאימה במיוחד לצוות של מסגרת מגורים, כי היא נשענת על השגרה היומית.'),
    ('DDP/PACE', 'Dyadic Developmental Psychotherapy: טיפול שמתמקד ביחסי הילד והמבוגר אחרי טראומת היקשרות.\nPACE היא הגישה היומיומית: שובבות (Playfulness), קבלה (Acceptance), סקרנות (Curiosity) ואמפתיה (Empathy).\nבשטח: מקבלים את הרגש, סקרנים לגבי מה שמאחורי ההתנהגות, ומחזיקים גבול בתוך הקשר.'),
    ('TF-CBT', 'Trauma-Focused CBT: טיפול קוגניטיבי-התנהגותי ממוקד טראומה, עם מחקר רב על יעילותו.\nכולל פסיכו-חינוך, מיומנויות הרגעה, זיהוי רגשות ומחשבות, נרטיב טראומה ובטיחות.\nהנרטיב עצמו נעשה רק אצל המטפל/ת; הצוות מתרגל עם הילד/ה את המיומנויות ביום-יום.'),
    ('Theraplay', 'Theraplay: טיפול דרך משחק משותף של מבוגר וילד, שבונה קשר והיקשרות.\nארבעה ממדים: מבנה, מעורבות, טיפוח ואתגר. משחקים קצרים, פשוטים ושמחים.\nמתאים לצוות: כמה דקות של משחק טיפוח או מעורבות ביום עושות הבדל.'),
    ('ויסות חושי', 'ויסות חושי: התאמת הסביבה והגירויים כדי שהגוף יוכל להירגע ולהשתתף.\nכלים: תנועה, לחץ עמוק (שמיכה כבדה), כדור לחיץ, הפחתת רעש ואור, פינה שקטה.\nקודם הגוף: ילד/ה מוצף/ת חושית לא יכול/ה ללמוד או להקשיב.'),
    ('NMT', 'Neurosequential Model of Therapeutics (פרי): התערבות לפי סדר ההתפתחות של המוח.\nהסדר: קודם ויסות (קצב, תנועה, ביטחון), אחר כך קשר, ורק אז חשיבה ולמידה (Regulate, Relate, Reason).\nבשטח: פעילויות קצביות וחוזרות, והרבה רגעים קצרים של קשר במשך היום.'),
]

def q(s):
    return "'" + str(s).replace("'", "''") + "'"
def arr(l):
    return "array[" + ", ".join(q(x) for x in l) + "]::text[]" if l else "'{}'::text[]"
def js(o):
    return q(json.dumps(o, ensure_ascii=False)) + "::jsonb"

themes = []
for f in sorted(glob.glob(os.path.join(ROOT, 'supabase', 'bank', '*.json'))):
    with io.open(f, encoding='utf-8') as h:
        themes.append(json.load(h))

errors, titles = [], {}
for t in themes:
    for g in t['goals']:
        if g['title'] in titles: errors.append('two goals named ' + g['title'])
        titles[g['title']] = t['theme']
        if sorted(g['ages']) != sorted(AGES): errors.append(g['title'] + ': ages ' + ','.join(g['ages']))
        for a, w in g['ages'].items():
            for k in GOAL_FIELDS:
                if not w.get(k): errors.append('%s %s: no %s' % (g['title'], a, k))
        if len(g.get('scale', [])) != 5: errors.append(g['title'] + ': the scale needs 5')
        for s in g.get('strengths', []):
            if len(s) > 20: errors.append(g['title'] + ': strength too long ' + s)
    for k in PARTS:
        p = t['parts'].get(k)
        if not p or sorted(p['ages']) != sorted(AGES): errors.append(t['theme'] + ': part ' + k)
for t in themes:
    for gt in t['plan']['goals']:
        if gt not in titles: errors.append(t['plan']['title'] + ': no goal ' + gt)
# the staff never in the child's gender: a slash word right after "אני" or a staff word is left as it is in the site; here only a warning
for t in themes:
    txt = json.dumps(t, ensure_ascii=False)
    for m in re.finditer(r'(?:המטפל/ת|מטפל/ת) (?!ו)[א-ת]+/[א-ת]+', txt):          # ("...עם המטפל/ת ומרגיש/ה" is the child: fine)
        errors.append(t['theme'] + ': a verb of the therapist with a slash: ' + m.group(0))
if errors:
    print('\n'.join(errors)); sys.exit(1)

out = ["-- scheduling v42 bank (2026-10-27): the content of the goal bank, written by Claude as drafts for the admin to check (Mercury decisions 97-118).",
       "-- Run once, after scheduling-v42.sql, on the TEST project. Safe to run again: an existing template keeps what was changed in it.",
       "-- Generated by tools/bank-sql.py from supabase/bank/*.json (edit there, not here).", ""]
up = "on conflict (scope, institution, kind, title) do update set description = excluded.description, themes = excluded.themes, category = excluded.category, methods = excluded.methods, content = excluded.content, draft = true where public.mercury_library.content is null;"
out.append("-- the treatment methods (a short card each)")
for name, desc in METHODS:
    out.append("insert into public.mercury_library (scope, kind, title, description, draft) values ('mercury', 'method', %s, %s, true) on conflict (scope, institution, kind, title) do nothing;" % (q(name), q(desc)))
skills, strengths = set(), set()
for t in themes:
    out.append(""); out.append("-- " + t['theme'])
    for g in t['goals']:
        th = [t['theme']] + g.get('also', [])
        content = {'bank': 1, 'review': g['review'], 'scale': g['scale'], 'avoid': g['avoid'], 'strengths': g['strengths'], 'skills': g['skills'], 'ages': g['ages']}
        skills.update(g['skills']); strengths.update(g['strengths'])
        out.append("insert into public.mercury_library (scope, kind, title, description, themes, category, methods, content, draft) values ('mercury', 'goal', %s, %s, %s, %s, %s, %s, true) %s"
                   % (q(g['title']), q(g['line']), arr(th), q(t['theme']), arr(g['methods']), js(content), up))
    for k in PARTS:
        p = t['parts'][k]
        out.append("insert into public.mercury_library (scope, kind, title, description, themes, category, content, draft) values ('mercury', %s, %s, %s, %s, %s, %s, true) %s"
                   % (q(k), q(p['title']), q(p['ages']['5-8']), arr([t['theme']]), q(t['theme']), js({'bank': 1, 'ages': p['ages']}), up))
    pl = t['plan']
    out.append("insert into public.mercury_library (scope, kind, title, description, themes, category, methods, content, draft) values ('mercury', 'plan', %s, %s, %s, %s, %s, %s, true) %s"
               % (q(pl['title']), q(pl['summary']), arr([t['theme']]), q(t['theme']), arr(pl.get('methods', [])),
                  js({'bank': 1, 'summary': pl['summary'], 'goal_titles': pl['goals'], 'parts': {k: t['parts'][k]['title'] for k in PARTS}}), up))
out.append(""); out.append("-- the skills and strengths the goals suggest (if the library has no such one yet)")
for s in sorted(skills):
    out.append("insert into public.mercury_library (scope, kind, title, draft) values ('mercury', 'skill', %s, false) on conflict (scope, institution, kind, title) do nothing;" % q(s))
for s in sorted(strengths):
    out.append("insert into public.mercury_library (scope, kind, title, draft) values ('mercury', 'strength', %s, false) on conflict (scope, institution, kind, title) do nothing;" % q(s))
out.append("")
out.append("select 'scheduling_v42_bank' as part, 'ok' as result, (select count(*) from public.mercury_library where scope = 'mercury' and kind = 'goal' and content ? 'ages') as goals, (select count(*) from public.mercury_library where draft) as drafts;")
with io.open(os.path.join(ROOT, 'supabase', 'scheduling-v42-bank.sql'), 'w', encoding='utf-8', newline='\n') as h:
    h.write('\n'.join(out) + '\n')
print('ok: %d themes, %d goals' % (len(themes), len(titles)))
